#!/usr/bin/env python3
"""Convert frame PNGs into the RGB565 tables in firmware/src/sprites.h.

Usage:
    python3 tools/png2sprites.py

Frames live in art/ and are listed per clip in CLIPS below. Clip order sets the
AnimState enum values, so the first entry becomes state 0.

The original PNGs for BOOT..HOT were lost; that art now only exists as the
generated FRAME_* arrays. When a clip's PNGs are missing, its arrays are copied
verbatim out of the existing sprites.h and a warning is printed, so a run with
only art/boot_logo.png present still emits a complete header.
"""

import re
import sys
from pathlib import Path

from PIL import Image

SPRITE_W = 128
SPRITE_H = 128
SPRITE_PIXELS = SPRITE_W * SPRITE_H
VALUES_PER_LINE = 12

REPO = Path(__file__).resolve().parent.parent
ART_DIR = REPO / "art"
OUT_PATH = REPO / "firmware" / "src" / "sprites.h"

# (clip name, source PNGs, milliseconds per frame)
CLIPS = [
    # The logo's 1.00x -> 1.05x scale-in is rendered at runtime, so one frame is
    # enough here; frame_ms is how long it holds on screen.
    ("LOGO", ["boot_logo.png"], 3500),
    (
        "BOOT",
        [
            "loading_screen_1.png",
            "loading_screen_2.png",
            "loading_screen_3.png",
            "loading_screen_4.png",
        ],
        600,
    ),
    ("COOLED", ["completely_cooled_down.png"], 1000),
    (
        "NEAR",
        [
            "Closer_to_operational_temp.png",
            "closer_to_operational_temp_2.png",
            "closer_to_operational_temp_3.png",
        ],
        300,
    ),
    ("COOLING", ["cooling_1.png", "cooling_2.png", "cooling_3.png"], 220),
    ("HOT", ["fire_1.png", "fire_2.png"], 180),
]

FRAME_RE = re.compile(
    r"(?:// (?P<source>[^\n]*)\n)?"
    r"const uint16_t FRAME_(?P<name>\w+)\[SPRITE_PIXELS\] PROGMEM = \{\n"
    r"(?P<body>.*?)\n\};",
    re.DOTALL,
)


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def png_to_body(path):
    """Return the formatted array body for one PNG."""
    image = Image.open(path).convert("RGBA")
    if image.size != (SPRITE_W, SPRITE_H):
        image = image.resize((SPRITE_W, SPRITE_H), Image.LANCZOS)

    # Transparency reads as black on the OLED, so composite rather than drop alpha.
    flat = Image.new("RGB", image.size, (0, 0, 0))
    flat.paste(image, mask=image.getchannel("A"))

    raw = flat.tobytes()
    words = [rgb565(raw[i], raw[i + 1], raw[i + 2]) for i in range(0, len(raw), 3)]
    if len(words) != SPRITE_PIXELS:
        sys.exit(f"{path.name}: expected {SPRITE_PIXELS} pixels, got {len(words)}")

    lines = []
    for start in range(0, len(words), VALUES_PER_LINE):
        chunk = words[start : start + VALUES_PER_LINE]
        lines.append("  " + " ".join(f"0x{w:04X}," for w in chunk))
    return "\n".join(lines)


def load_existing_frames():
    """Map clip name -> ordered list of (source comment, array body) from sprites.h."""
    if not OUT_PATH.exists():
        return {}

    clips = {}
    for match in FRAME_RE.finditer(OUT_PATH.read_text()):
        clip, _, index = match.group("name").rpartition("_")
        if not clip or not index.isdigit():
            continue
        clips.setdefault(clip, []).append(
            (int(index), match.group("source"), match.group("body"))
        )

    return {
        clip: [(source, body) for _, source, body in sorted(frames)]
        for clip, frames in clips.items()
    }


def build_clip(name, sources, existing):
    """Convert the clip's PNGs, or reuse the arrays already in sprites.h."""
    paths = [ART_DIR / source for source in sources]
    missing = [path.name for path in paths if not path.exists()]

    if not missing:
        return [(path.name, png_to_body(path)) for path in paths]

    if name in existing:
        print(
            f"WARNING: {name} falling back to the {len(existing[name])} FRAME_{name}_* "
            f"array(s) already in sprites.h; missing from {ART_DIR.name}/: "
            f"{', '.join(missing)}",
            file=sys.stderr,
        )
        return existing[name]

    sys.exit(
        f"{name}: no PNGs in {ART_DIR} ({', '.join(missing)}) and no existing "
        f"FRAME_{name}_* arrays to fall back on"
    )


def main():
    existing = load_existing_frames()
    clips = [(name, build_clip(name, sources, existing), ms) for name, sources, ms in CLIPS]

    out = [
        "// Generated by tools/png2sprites.py — do not edit by hand.",
        "#pragma once",
        "#include <Arduino.h>",
        "#include <stdint.h>",
        "",
        f"static const int SPRITE_W = {SPRITE_W};",
        f"static const int SPRITE_H = {SPRITE_H};",
        f"static const int SPRITE_PIXELS = {SPRITE_PIXELS};",
        "",
    ]

    for name, frames, _ in clips:
        for index, (source, body) in enumerate(frames):
            if source:
                out.append(f"// {source}")
            out.append(f"const uint16_t FRAME_{name}_{index}[SPRITE_PIXELS] PROGMEM = {{")
            out.append(body)
            out.append("};")
            out.append("")

    out.append("enum AnimState : uint8_t {")
    for value, (name, _, _) in enumerate(clips):
        out.append(f"  ANIM_{name} = {value},")
    out.append("};")
    out.append(f"static const uint8_t ANIM_STATE_COUNT = {len(clips)};")
    out.append("")

    for name, frames, _ in clips:
        members = ", ".join(f"FRAME_{name}_{i}" for i in range(len(frames)))
        out.append(f"static const uint16_t *const CLIP_{name}[] = {{ {members} }};")
    out.append("")

    out.extend([
        "struct AnimClip {",
        "  const uint16_t *const *frames;",
        "  uint8_t count;",
        "  uint16_t frame_ms;",
        "};",
        "",
        "static const AnimClip ANIM_CLIPS[ANIM_STATE_COUNT] = {",
    ])
    for name, frames, frame_ms in clips:
        out.append(f"  {{ CLIP_{name}, {len(frames)}, {frame_ms} }},")
    out.append("};")
    out.append("")

    out.extend([
        "inline const AnimClip &animClip(AnimState s) {",
        "  return ANIM_CLIPS[s < ANIM_STATE_COUNT ? s : 0];",
        "}",
        "",
        "inline const uint16_t *animFrame(AnimState s, uint8_t i) {",
        "  const AnimClip &c = animClip(s);",
        "  return c.frames[i % c.count];",
        "}",
        "",
    ])

    OUT_PATH.write_text("\n".join(out))
    total = sum(len(frames) for _, frames, _ in clips)
    print(f"Wrote {OUT_PATH.relative_to(REPO)} — {len(clips)} clips, {total} frames")


if __name__ == "__main__":
    main()
